export type MessageKey = keyof typeof messages['pt-BR']

function readStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'pt-BR'
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    return stored === 'en' || stored === 'pt-BR' ? stored : 'pt-BR'
  } catch {
    return 'pt-BR'
  }
}

const locale = ref<Locale>(readStoredLocale())

function applyLocale(nextLocale: Locale) {
  if (typeof document !== 'undefined') document.documentElement.lang = nextLocale
}

applyLocale(locale.value)

export function useLocale() {
  function setLocale(nextLocale: Locale) {
    locale.value = nextLocale
    applyLocale(nextLocale)
    if (typeof window !== 'undefined') {
      try {
        window.localStorage.setItem(STORAGE_KEY, nextLocale)
      } catch {
        // A blocked storage should not prevent language switching.
      }
    }
  }

  function toggleLocale() {
    setLocale(locale.value === 'pt-BR' ? 'en' : 'pt-BR')
  }

  function t(key: MessageKey): string {
    return messages[locale.value][key]
  }

  return {
    locale,
    isEnglish: computed(() => locale.value === 'en'),
    setLocale,
    toggleLocale,
    t,
  }
}
